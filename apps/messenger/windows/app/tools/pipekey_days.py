"""pipekey_days.py VECTORS OUT: the day rows of the iOS 2311 vectors (vectors_2311.py --json VECTORS) as the Rust table of
src-tauri/src/pipekey/days.rs, read by pipekey/tests.rs."""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src, encoding="utf-8"))
DAYS = ["20754", "20755", "20757", "20758", "20759", "20760", "20762"]


def mark(r):
    s = r["status"]
    if s.startswith("confirmed"):
        return "C"
    if s.startswith("rule"):
        return "R"
    return "D"


def q(rows, prefix):
    for r in rows:
        if r["quantity"].startswith(prefix):
            return r
    raise KeyError(prefix)


def strs(v):
    return "&[" + ", ".join('"%s"' % x for x in v) + "]"


lines = [
    "// GENERATED by app/tools/pipekey_days.py from app/tools/vectors_2311.py --json (exit 0: every value the 2311 tree states",
    "// reproduces). Each value carries its mark: [C] asserted by 2311's own checks (MTPipeKey.swift:313-379, MontanaTests),",
    "// [D] derived from the 2311 formula in Python apart from this code, [R] a rule read off the source.",
    "",
    "pub struct Lay { pub w: i64, pub laid: &'static str, pub old: &'static str, pub accepted: &'static [&'static str], pub marks: &'static str }",
    "pub struct Floor { pub day: i64, pub value: &'static str, pub record: &'static str, pub sha: &'static str, pub head: &'static str }",
    "pub struct Day {",
    "    pub d: i64,",
    "    pub walked: (&'static str, char),",
    "    pub item_root: bool,",
    "    pub lays: [Lay; 4],",
    "    pub index: &'static [&'static str],",
    "    pub conv_w: (&'static str, char),",
    "    pub box_days: [&'static str; 4],",
    "    pub body: [(i64, &'static str, char); 3],",
    "    pub letter_author: &'static str,",
    "    pub with_author: &'static str,",
    "    pub group_au: &'static str,",
    "    pub group_au_2308: &'static str,",
    "    pub reader_takes_2308: bool,",
    "    pub reader_keys: usize,",
    "    pub same_ask: (&'static str, &'static [&'static str], &'static str),",
    "    pub same_yes: (&'static str, &'static [&'static str], &'static str),",
    "    pub rank_a: &'static str,",
    "    pub rank_b: &'static str,",
    "    pub blind: &'static str,",
    "    pub floor: Option<Floor>,",
    "}",
    "",
    "pub const DAYS: [Day; %d] = [" % len(DAYS),
]
for day in DAYS:
    rows = d["days"][day]["rows"]
    w = q(rows, "pipe_secret(day)")
    lays = []
    for m in (0, 5, 720, 1439):
        laid = q(rows, "tag 2311 lays, minute %d " % m)
        old = q(rows, "old tag over the established secret, minute %d " % m)
        acc = [r for r in rows if r["quantity"].startswith("tags a 2311 receiver accepts in W=") and r is not None]
        wv = int(laid["quantity"].split("W=")[1].split(",")[0])
        acc = q(rows, "tags a 2311 receiver accepts in W=%d" % wv)
        lays.append('Lay { w: %d, laid: "%s", old: "%s", accepted: %s, marks: "%s%s%s" }'
                    % (wv, laid["value"], old["value"], strs(acc["value"]), mark(laid), mark(old), mark(acc)))
    idx = q(rows, "tag index at the day's first minute")
    cw = q(rows, "conv_w(D)")
    boxd = q(rows, "conv_w over the box days")
    bodies = []
    for m in (0, 5, 1439):
        r = q(rows, "body key, minute %d " % m)
        wv = int(r["quantity"].split("W=")[1].rstrip(")"))
        bodies.append('(%d, "%s", \'%s\')' % (wv, r["value"], mark(r)))
    la = q(rows, "letter author tag, person")
    wa = q(rows, "withAuthor(empty body) bytes")
    ga = q(rows, "group author tag (ownTag)")
    g8 = q(rows, "group author tag a 2308 build lays")
    rt = q(rows, "2311 reader takes the 2308 group tag")
    rk = q(rows, "keys a 2311 reader tries")
    sa = (q(rows, "mt-same-ask: older"), q(rows, "mt-same-ask: what 2311 accepts"), q(rows, "mt-same-ask: what 2308 lays"))
    sy = (q(rows, "mt-same-yes: older"), q(rows, "mt-same-yes: what 2311 accepts"), q(rows, "mt-same-yes: what 2308 lays"))
    ra, rb = q(rows, "mt-same-rank A"), q(rows, "mt-same-rank B")
    bl = q(rows, "coin SEND blind")
    item = q(rows, "item key of the day")
    try:
        fd = q(rows, "floor day F")
        fl = 'Some(Floor { day: %d, value: "%s", record: "%s", sha: "%s", head: "%s" })' % (
            fd["value"], q(rows, "floor value")["value"], q(rows, "floor record, 249")["value"], q(rows, "SHA-256 of the floor")["value"],
            q(rows, "archive head")["value"])
    except KeyError:
        fl = "None"
    lines.append("    // %s %s, %s" % (day, d["days"][day]["date"], d["days"][day]["phase"]))
    lines.append("    Day {")
    lines.append("        d: %s," % day)
    lines.append('        walked: ("%s", \'%s\'),' % (w["value"], mark(w)))
    lines.append("        item_root: %s," % ("true" if item["value"] == "root" else "false"))
    lines.append("        lays: [")
    for l in lays:
        lines.append("            %s," % l)
    lines.append("        ],")
    lines.append("        index: %s, // [%s]" % (strs(idx["value"]), mark(idx)))
    lines.append('        conv_w: ("%s", \'%s\'),' % (cw["value"], mark(cw)))
    lines.append("        box_days: [%s], // [%s]" % (", ".join('"%s"' % x for x in boxd["value"]), mark(boxd)))
    lines.append("        body: [%s]," % ", ".join(bodies))
    lines.append('        letter_author: "%s", // [%s]' % (la["value"], mark(la)))
    lines.append('        with_author: "%s", // [%s]' % (wa["value"], mark(wa)))
    lines.append('        group_au: "%s", // [%s]' % (ga["value"], mark(ga)))
    lines.append('        group_au_2308: "%s", // [%s]' % (g8["value"], mark(g8)))
    lines.append("        reader_takes_2308: %s, // [%s]" % ("true" if rt["value"] else "false", mark(rt)))
    lines.append("        reader_keys: %d, // [R]" % len(rk["value"]))
    lines.append('        same_ask: ("%s", %s, "%s"), // [D]' % (sa[0]["value"], strs(sa[1]["value"]), sa[2]["value"]))
    lines.append('        same_yes: ("%s", %s, "%s"), // [D]' % (sy[0]["value"], strs(sy[1]["value"]), sy[2]["value"]))
    lines.append('        rank_a: "%s", // [%s]' % (ra["value"], mark(ra)))
    lines.append('        rank_b: "%s", // [%s]' % (rb["value"], mark(rb)))
    lines.append('        blind: "%s", // [%s]' % (bl["value"], mark(bl)))
    lines.append("        floor: %s, // [D]" % fl)
    lines.append("    },")
lines.append("];")
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("wrote", out, len(lines))
